// Interface language. Chinese source text doubles as the lookup key, so a missing
// English entry falls back to Chinese instead of showing a blank.
export type Language = 'zh' | 'en';
export type LanguagePreference = 'auto' | Language;

let current: Language = 'zh';

export function resolveLanguage(preference: LanguagePreference | undefined): Language {
  if (preference === 'zh' || preference === 'en') return preference;
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

/** Set before rendering; components read it through t() during render. */
export function setLanguage(language: Language) {
  current = language;
  document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN';
}

export const locale = () => current === 'en' ? 'en-US' : 'zh-CN';

export function t(key: string, ...args: unknown[]): string {
  const text = current === 'en' ? en[key] ?? key : key;
  return args.length ? text.replace(/\{(\d+)\}/g, (_, index: string) => String(args[Number(index)])) : text;
}

